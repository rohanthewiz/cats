// This is the far end of the chain every structured key event takes:
//
//	KeyboardEvent.code                   (a browser reports this verbatim —
//	                                      cmd/catway/web/js/20-keys.js)
//	  → wire.Key{Code: "KeyA"}           (the wire)
//	    → w3cKeyName → ParseKey          (this file's subject)
//	      → VT bytes                     (encoder.go)
//
// The chain used to have a second head: the Flutter phone reported
// PhysicalKeyboardKey.usbHidUsage and a table generated by cmd/catgen-dart
// (kUsbHidToW3cCode, committed as keys.g.dart) turned it into a W3C code. That
// head is gone with 5add396 — cats-mobile is Go on grmob, imports wire
// directly, and sends no wire.Key at all (its composer types text through
// pane.send_input). No USB HID → W3C table exists in Go anywhere, so the
// USB-usage half of the old checks had nothing left to guard and was dropped.
//
// The half that survives is the one that tests live code: w3cKeyName feeding
// libghostty.ParseKey. The browser forwards e.code without filtering, so any
// code a keyboard can produce reaches that conversion. A code that reaches
// ghostty and does not parse is not an error anyone sees — encoder.go falls
// back to KeyUnidentified — it is a key that silently does nothing, which is
// the worst failure mode a keyboard can have.

