func TestW3CCodesReachGhostty(t *testing.T) {
	// Guard the fixture itself: a truncated or duplicated list would let the
	// partition pass by checking less than it claims to.
	seen := make(map[string]bool, len(knownW3CCodes))
	for _, code := range knownW3CCodes {
		if seen[code] {
			t.Errorf("%q appears twice in knownW3CCodes", code)
		}
		seen[code] = true
	}
	if len(knownW3CCodes) < 200 {
		t.Fatalf("knownW3CCodes has only %d entries; the fixture was truncated",
			len(knownW3CCodes))
	}

	expectedUnknown := make(map[string]bool, len(ghosttyUnknownCodes))
	for _, code := range ghosttyUnknownCodes {
		if !seen[code] {
			// An unknown code outside the universe would never be exercised, so
			// the "now parses" check below could not fire for it.
			t.Errorf("%q is in ghosttyUnknownCodes but not in knownW3CCodes", code)
		}
		expectedUnknown[code] = true
	}

	unparsed := map[string]bool{}
	reached := 0
	for _, code := range knownW3CCodes {
		if _, err := libghostty.ParseKey(w3cKeyName(code)); err != nil {
			unparsed[code] = true
			continue
		}
		reached++
	}

	// Both directions are failures, for different reasons.
	for code := range unparsed {
		if !expectedUnknown[code] {
			t.Errorf("%q → w3cKeyName %q no longer reaches ghostty. A client pressing "+
				"this key would silently do nothing — encoder.go falls back to "+
				"KeyUnidentified rather than erroring.", code, w3cKeyName(code))
		}
	}
	for _, code := range ghosttyUnknownCodes {
		if !unparsed[code] {
			t.Errorf("%q is listed in ghosttyUnknownCodes but now parses — "+
				"ghostty grew support for it; drop it from the list", code)
		}
	}
	t.Logf("%d of %d W3C codes reach libghostty.ParseKey", reached, len(knownW3CCodes))
}

// TestCommonKeysSurviveTheChain spot-checks the keys a client actually sends,
// naming them explicitly so the test does not depend on knownW3CCodes being
// complete — a fixture edited down to nothing cannot pass by having nothing to
// check.
//
// The old version also pinned each key's USB HID usage (0x7xxxx) to its code;
// that half guarded the generated Dart table and went with it. Home and End
// are here because 20-keys.js synthesizes them (⌘←/⌘→) rather than forwarding
// e.code, so they reach the encoder even from a keyboard without those keys.
func TestCommonKeysSurviveTheChain(t *testing.T) {
	common := []string{
		"KeyA", "KeyZ", "Digit1", "Enter", "Escape", "Backspace", "Tab", "Space",
		"F1", "F12", "ArrowRight", "ArrowLeft", "ArrowDown", "ArrowUp",
		"Home", "End",
		"ControlLeft", "ShiftLeft", "AltLeft", "MetaLeft",
	}
	for _, code := range common {
		if _, err := libghostty.ParseKey(w3cKeyName(code)); err != nil {
			t.Errorf("%q does not reach ghostty: %v", code, err)
		}
	}
}
