// writeClaudeTranscript lays down a transcript under claude's projects tree, in
// a slug directory the reader has to find by glob.
func writeClaudeTranscript(t *testing.T, root, id string, lines ...string) {
	t.Helper()
	dir := filepath.Join(root, "projects", "-Users-x-proj")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	body := strings.Join(lines, "\n") + "\n"
	if err := os.WriteFile(filepath.Join(dir, id+".jsonl"), []byte(body), 0o600); err != nil {
		t.Fatalf("write: %v", err)
	}
}

// userRecord is a transcript user record with a plain-string content, the shape
// both prompts and command records take.
func userRecord(at time.Time, content string) string {
	return `{"type":"user","timestamp":"` + at.UTC().Format(time.RFC3339Nano) +
		`","message":{"role":"user","content":` + quoteJSON(content) + `}}`
}

func quoteJSON(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`)
	return `"` + r.Replace(s) + `"`
}

// The records claude writes at the top of a conversation started by /clear,
// copied from a real transcript: untimestamped bookkeeping, a caveat, then the
// command itself.
func clearedHead(at time.Time) []string {
	return []string{
		`{"type":"mode","mode":"default","sessionId":"x"}`,
		`{"type":"file-history-snapshot","messageId":"m","snapshot":{}}`,
		userRecord(at.Add(9*time.Millisecond), "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"),
		userRecord(at, "<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>"),
	}
}

func TestAgentSessionOfCarriesPIDAndStart(t *testing.T) {
	root := t.TempDir()
	t.Setenv("CLAUDE_CONFIG_DIR", root)
	writeClaudeSession(t, root, 4242, `{"pid":4242,"sessionId":"sess-a","startedAt":1791748488290}`)

	got := AgentSessionOf("claude", []int{4241, 4242})
	if got.PID != 4242 || got.ID != "sess-a" || !got.StartedAt.Equal(time.UnixMilli(1791748488290)) {
		t.Fatalf("AgentSessionOf = %+v", got)
	}
	// An entry without startedAt still answers; the start is just unknown.
	writeClaudeSession(t, root, 4243, `{"pid":4243,"sessionId":"sess-b"}`)
	if got := AgentSessionOf("claude", []int{4243}); got.ID != "sess-b" || !got.StartedAt.IsZero() {
		t.Fatalf("no startedAt: %+v", got)
	}
}

// Each way a conversation can begin, told apart from the registry and the
// transcript alone — what a pane without the hook integration has to go on.
func TestClaudeSessionOrigin(t *testing.T) {
	root := t.TempDir()
	t.Setenv("CLAUDE_CONFIG_DIR", root)

	start := time.Date(2026, 10, 11, 12, 0, 0, 0, time.UTC)
	prev := AgentSession{PID: 100, ID: "sess-old", StartedAt: start}
	seen := start.Add(30 * time.Minute) // the old id was still there at this read

	// Fresh launch: new pid, and its transcript (if any yet) postdates it.
	writeClaudeTranscript(t, root, "sess-fresh", userRecord(start.Add(time.Hour+time.Second), "hello"))
	fresh := AgentSession{PID: 200, ID: "sess-fresh", StartedAt: start.Add(time.Hour)}
	if got := AgentSessionOrigin("claude", fresh, prev, seen); got != SessionOriginStartup {
		t.Errorf("fresh launch = %q, want startup", got)
	}
	// …including before claude has written the transcript at all.
	unwritten := AgentSession{PID: 201, ID: "sess-unwritten", StartedAt: start.Add(time.Hour)}
	if got := AgentSessionOrigin("claude", unwritten, AgentSession{}, time.Time{}); got != SessionOriginStartup {
		t.Errorf("fresh launch, no transcript = %q, want startup", got)
	}

	// /clear: same pid, a new id whose records all postdate the last read of the old.
	writeClaudeTranscript(t, root, "sess-cleared", clearedHead(seen.Add(time.Second))...)
	cleared := AgentSession{PID: 100, ID: "sess-cleared", StartedAt: start}
	if got := AgentSessionOrigin("claude", cleared, prev, seen); got != SessionOriginClear {
		t.Errorf("/clear = %q, want clear", got)
	}
	// Same pid with no transcript yet is still a new conversation inside the
	// running agent — nothing else moves a process to a fresh id.
	quiet := AgentSession{PID: 100, ID: "sess-quiet", StartedAt: start}
	if got := AgentSessionOrigin("claude", quiet, prev, seen); got != SessionOriginClear {
		t.Errorf("same pid, no transcript = %q, want clear", got)
	}
	// No previous observation to compare pids with (the host just started): the
	// /clear marker is what keeps a long-running cleared session from reading as
	// a fresh launch.
	if got := AgentSessionOrigin("claude", cleared, AgentSession{}, time.Time{}); got != SessionOriginClear {
		t.Errorf("/clear, no previous = %q, want clear", got)
	}

	// /resume inside the running agent: same pid, history from before the switch —
	// even one that began after the process did, which is why the reference for
	// the same pid is the last read and not the process start.
	writeClaudeTranscript(t, root, "sess-earlier", userRecord(start.Add(10*time.Minute), "earlier work"))
	resumedHere := AgentSession{PID: 100, ID: "sess-earlier", StartedAt: start}
	if got := AgentSessionOrigin("claude", resumedHere, prev, seen); got != SessionOriginResume {
		t.Errorf("/resume = %q, want resume", got)
	}
	// A resumed conversation that itself began with a /clear is still a resume:
	// the history test runs first.
	writeClaudeTranscript(t, root, "sess-old-cleared", clearedHead(start.Add(5*time.Minute))...)
	resumedCleared := AgentSession{PID: 100, ID: "sess-old-cleared", StartedAt: start}
	if got := AgentSessionOrigin("claude", resumedCleared, prev, seen); got != SessionOriginResume {
		t.Errorf("/resume of a cleared session = %q, want resume", got)
	}

	// `claude --resume`: a new pid holding history from before it started.
	resumedLaunch := AgentSession{PID: 300, ID: "sess-earlier", StartedAt: start.Add(2 * time.Hour)}
	if got := AgentSessionOrigin("claude", resumedLaunch, prev, seen); got != SessionOriginResume {
		t.Errorf("--resume launch = %q, want resume", got)
	}

	// No probe for the agent, or no conversation: no answer.
	if got := AgentSessionOrigin("copilot", fresh, prev, seen); got != "" {
		t.Errorf("copilot = %q, want \"\"", got)
	}
	if got := AgentSessionOrigin("claude", AgentSession{PID: 1}, prev, seen); got != "" {
		t.Errorf("no id = %q, want \"\"", got)
	}
}

// The head parse takes the oldest timestamp, not the first, and only counts a
// /clear that is a command record — a prompt that merely mentions it, as a block
// list or in prose, is not one.
func TestParseClaudeTranscriptHead(t *testing.T) {
	at := time.Date(2026, 9, 27, 2, 45, 25, 684e6, time.UTC)
	head := parseClaudeTranscriptHead([]byte(strings.Join(clearedHead(at), "\n") + "\n" + `{"type":"user","timest`))
	if !head.cleared || !head.earliest.Equal(at) {
		t.Fatalf("cleared head = %+v, want cleared at %v", head, at)
	}

	blocks := `{"type":"user","timestamp":"2026-09-27T02:45:25Z","message":{"content":[{"type":"text","text":"<command-name>/clear</command-name>"}]}}`
	if head := parseClaudeTranscriptHead([]byte(blocks)); head.cleared {
		t.Error("block-list content must not count as a /clear command")
	}
	prose := userRecord(at, "why does /clear lose my history?")
	if head := parseClaudeTranscriptHead([]byte(prose)); head.cleared {
		t.Error("a prompt mentioning /clear must not count")
	}
	assistant := `{"type":"assistant","timestamp":"2026-09-27T02:45:25Z","message":{"content":"<command-name>/clear</command-name>"}}`
	if head := parseClaudeTranscriptHead([]byte(assistant)); head.cleared {
		t.Error("only user records carry commands")
	}
}

func TestNormalizeSessionOrigin(t *testing.T) {
	for in, want := range map[string]string{
		"startup": "startup", "clear": "clear", "resume": "resume",
		"compact": "", "": "", "Startup": "", "other": "",
	} {
		if got := NormalizeSessionOrigin(in); got != want {
			t.Errorf("NormalizeSessionOrigin(%q) = %q, want %q", in, got, want)
		}
	}
}

// When the pane entered a conversation: the process start for a launch, the
// moment of the read for a switch inside a running agent.
func TestAgentSessionBegan(t *testing.T) {
	start := time.Date(2026, 10, 11, 12, 0, 0, 0, time.UTC)
	now := start.Add(time.Hour)
	prev := AgentSession{PID: 100, ID: "sess-old", StartedAt: start}
	for _, c := range []struct {
		name      string
		cur, prev AgentSession
		want      time.Time
	}{
		{"launch takes the process start", AgentSession{PID: 200, ID: "b", StartedAt: start.Add(50 * time.Minute)}, prev, start.Add(50 * time.Minute)},
		{"first sighting takes the process start", AgentSession{PID: 200, ID: "b", StartedAt: start.Add(50 * time.Minute)}, AgentSession{}, start.Add(50 * time.Minute)},
		{"switch in the same process takes the read", AgentSession{PID: 100, ID: "b", StartedAt: start}, prev, now},
		{"no process start known", AgentSession{PID: 200, ID: "b"}, prev, now},
		{"a start in the future is not believed", AgentSession{PID: 200, ID: "b", StartedAt: now.Add(time.Minute)}, prev, now},
	} {
		if got := AgentSessionBegan(c.cur, c.prev, now); !got.Equal(c.want) {
			t.Errorf("%s: got %v, want %v", c.name, got, c.want)
		}
	}
}
